def get_industry_name(code: str) -> str:
    """Return the Chinese name for a given industry code, or the code itself if not found."""
    return INDUSTRY_MAP.get(code, code)


def get_industry_names(codes: list[str] | str | None) -> str:
    """
    Convert a list of industry codes (or JSON string thereof) to Chinese names,
    joined by comma. Returns '' if no valid codes.
    """
    if not codes:
        return ""
    if isinstance(codes, str):
        import json
        try:
            codes = json.loads(codes)
        except (json.JSONDecodeError, TypeError):
            return ""
    if not isinstance(codes, list):
        return ""
    names = [get_industry_name(c) for c in codes if c]
    return ", ".join(n for n in names if n)


def get_all_categories() -> list[dict]:
    """Return the 20 top-level categories for dropdown display."""
    return [{"code": k, "name": v} for k, v in CATEGORY_MAP.items()]


def get_industries_by_category(category_code: str) -> list[dict]:
    """Return all industries under a given category (first letter)."""
    return [
        {"code": k, "name": v}
        for k, v in INDUSTRY_MAP.items()
        if k.startswith(category_code)
    ]


def get_all_industries_grouped() -> list[dict]:
    """Return all industries grouped by category for tree/two-level dropdown."""
    result = []
    for cat_code, cat_name in CATEGORY_MAP.items():
        children = get_industries_by_category(cat_code)
        if children:
            result.append({
                "code": cat_code,
                "name": cat_name,
                "children": children,
            })
    return result
